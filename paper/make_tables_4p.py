"""Generates paper/tables/table1_data.tex and table_results_4p.tex from paper/numbers.csv (column `label` -> `value`).
Usage: python paper/make_tables_4p.py paper/numbers.csv <tables_dir>
Table 1 (single column): questions per split (test images), closed-form, yes/no; VQA-RAD re-split by image.
Table 2 (page width): per benchmark x family, A_text (SD), PubMedBERT, TF-IDF, grey (VLM only), G_enc [CI], G_ft [CI], G [CI], A - A_swap [CI].
Labels of the paper only; layout-only edits go to the copy in tables/."""

import re, sys, pathlib, hashlib, csv
numbers = pathlib.Path(sys.argv[1]); out = pathlib.Path(sys.argv[2]); out.mkdir(parents=True, exist_ok=True)
SHA = hashlib.sha256(numbers.read_bytes()).hexdigest()[:12]
rows = {}
with open(numbers, newline="", encoding="utf-8") as fh:
    for r in csv.DictReader(fh): rows[r["label"]] = r["value"]   # last occurrence wins, as in the original generator
def get(label):
    assert label in rows, f"row not encontrada in the folha: {label}"
    return rows[label]
def fmt(n): return f"{int(n):,}".replace(",", "\\,")
def sgn(v):
    v = v.strip()
    if v in ("+0.0", "-0.0"): return "0.0"
    return ("$-$" + v[1:]) if v.startswith("-") else ("$+$" + v[1:] if v.startswith("+") else v)
def msd(s):
    m = re.match(r'([+\-]?\d+\.\d+) \((\d+\.\d+)\)', s.strip()); assert m, s; return m.group(1), m.group(2)
def ci(s):
    m = re.match(r'\[([+\-]?\d+\.\d+), ([+\-]?\d+\.\d+)\]', s.strip()); assert m, s
    def c(x): x = x.strip(); return ("$-$" + x[1:]) if x.startswith("-") else x.lstrip("+")
    return f"{c(m.group(1))}, {c(m.group(2))}"
def cell(mean, cis): return f"\\makecell{{{mean}\\\\{cis}}}"
HDR = "%% GENERATED by paper/make_tables_4p.py from paper/numbers.csv (sha256 %s). Do not edit numbers by hand." % SHA
# ---------- Tabela 1 ----------
L = [HDR, r"\begin{table}[t]", r"\centering\small\setlength{\tabcolsep}{3pt}",
     r"\caption{Questions per split (test images in parentheses) and closed-form test questions. VQA-RAD: re-split by image.}",
     r"\label{tab:data}", r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
     r"Benchmark & Train & Val. & Test (images) & Closed \\", r"\midrule"]
SPL = [("Kvasir-VQA-x1", "Kvasir-VQA-x1 · VLM and M3AE", "KVASIR"), ("SLAKE", "SLAKE · M3AE", "SLAKE"), ("HEAL-MedVQA", "HEAL-MedVQA · VLM and M3AE", "HEAL"), ("Medical-Diff-VQA", "Medical-Diff-VQA · VLM and M3AE", "MIMIC")]
for name, pref, zk in SPL:
    tr = get(f"{pref} · train · questions").replace(" ", "\\,"); va = get(f"{pref} · val · questions").replace(" ", "\\,")
    te = get(f"{pref} · test · questions").replace(" ", "\\,"); im = get(f"{pref} · test · images").replace(" ", "\\,")
    nc, ny = [int(x) for x in get(f"{zk}: closed-form questions (answer_type of the arrow) / yes/no only (gold yes/no)").split(" / ")]
    L.append(f"{name} & {tr} & {va} & {te} ({im}) & {fmt(nc)} \\\\")
tr = get("VQA-RAD re-split / train: questions / images / closed-form / yes/no").split(" / ")
va = get("VQA-RAD re-split / validation: questions / images / closed-form / yes/no").split(" / ")
te = get("VQA-RAD re-split / test: questions / images / closed-form / yes/no").split(" / ")
L.append(f"VQA-RAD & {fmt(tr[0])} & {fmt(va[0])} & {fmt(te[0])} ({fmt(te[1])}) & {fmt(te[2])} \\\\")
L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
(out / "table1_data.tex").write_text("\n".join(L) + "\n")
SUF = " [M3AE no-image]"   # r42 (23/10): A_text, G_enc e G do M3AE pela secao 13 da folha (m3ae_no_image_atext; copia m3ae_no_image_atext/make_tables_candidate.py)
# ---------- Tabela 2 ----------
BASES = [("KVASIR", "Kvasir-VQA-x1"), ("SLAKE", "SLAKE"), ("HEAL", "HEAL-MedVQA"), ("MIMIC", "Medical-Diff-VQA"), ("VQA-RAD (re-split by image; paper's benchmark)", "VQA-RAD")]
FAM = [("Qwen2-VL-2B", "Qwen2-VL-2B"), ("SmolVLM2-2.2B", "SmolVLM2-2.2B"), ("M3AE", "M3AE")]
NQ = {"KVASIR": 10779, "SLAKE": 416, "HEAL": 1446, "MIMIC": 1499, "VQA-RAD (re-split by image; paper's benchmark)": 418}
# r16 (20/10): uma linha por modelo; intervalo ao lado da media; sem "+"; base como linha de grupo
def nosign(v):
    v = v.strip()
    if v in ("+0.0", "-0.0"): return "0.0"
    return ("$-$" + v[1:]) if v.startswith("-") else v.lstrip("+")
def ci1(s):
    m = re.match(r'\[([+\-]?\d+\.\d+), ([+\-]?\d+\.\d+)\]', s.strip()); assert m, s
    keep = lambda v: ("$-$" + v[1:]) if v.startswith("-") else v.lstrip("+")  # nos limites do IC o -0.0 fica (como na r15)
    return f"[{keep(m.group(1))}, {keep(m.group(2))}]"
CIFONT = r"\footnotesize"
def cell1(mean, cis): return f"{nosign(mean)} {{{CIFONT}{cis}}}"
L = [HDR, r"\begin{table*}[t]", r"\centering\small\setlength{\tabcolsep}{3pt}",
     r"\caption{Closed-form questions, per benchmark and family: $\Atext$ (mean (SD) over three seeds); PubMedBERT, TF-IDF and grey-image baselines; gains and drop $A - A_{\mathrm{swap}}$, as mean over three seeds [95\,\% CI of the mean over images and seeds]. Accuracy in \%, gains in pp; differences are computed before rounding. M3AE: no image path for $\Atext$, ViT frozen for $\Afrozen$, full fine-tuning for $\Aft$.}",
     r"\label{tab:main}", r"\begin{tabular}{@{}lrrrrp{4pt}llll@{}}", r"\toprule",
     r" & \multicolumn{4}{c}{baselines} & & \multicolumn{4}{c}{gains and swap drop} \\",
     r"\cmidrule(lr){2-5}\cmidrule(lr){7-10}",
     r"Model & $\Atext$ & PubMedBERT & TF-IDF & Grey & & $\Genc$ & $\Gft$ & $G$ & $A - A_{\mathrm{swap}}$ \\", r"\midrule"]
for bi, (bkey, bname) in enumerate(BASES):
    L.append(r"\multicolumn{10}{@{}l}{\textit{%s}} \\" % bname)
    for fi, (fkey, fname) in enumerate(FAM):
        base = get(f"{bkey} / {fkey} (n={NQ[bkey]}): A_text / TF-IDF / PubMedBERT / majority (%)" + (SUF if fkey == "M3AE" else "")).split(" / ")
        at_m, at_s = msd(base[0]); tf, _ = msd(base[1]); pb, _ = msd(base[2])
        if fkey != "M3AE":
            g = get(f"{bkey} / {fkey} (same set, n={NQ[bkey]}): A_text / TF-IDF / PubMedBERT / grey image (%); A_text - grey image (pp)")
            grey, _ = msd(g.split("; ")[0].split(" / ")[3])
            gains = get(f"{bkey} / {fkey}: G_enc / G_ft / G (pp)").split(" / ")
            cis = get(f"{bkey} / {fkey}: joint CI (images and seeds) of G_enc / G_ft / G (pp)").split(" / ")
            genc = cell1(msd(gains[0])[0], ci1(cis[0])); gft = cell1(msd(gains[1])[0], ci1(cis[1])); gg = cell1(msd(gains[2])[0], ci1(cis[2]))
        else:
            # r37 (21/10): cinza do M3AE = modelo de encoder congelado avaliado com imagem cinza so no teste (secao 1e; media)
            grey, _ = msd(get(f"{bkey} / M3AE frozen encoder: grey image at test time only, mean (SD) / per seed (%)").split(" / ")[0])
            gm = get(f"{bkey} / M3AE: G (pp)" + SUF); gc = get(f"{bkey} / M3AE: joint CI (images and seeds) of G (pp)" + SUF)
            # r32 (21/10): G_enc e G_ft do M3AE pela secao 1e (encoder visual congelado); G conferido contra a linha publicada
            fz = get(f"{bkey} / M3AE frozen encoder: G_enc / G_ft / G (pp)" + SUF).split(" / ")
            fzc = get(f"{bkey} / M3AE frozen encoder: joint CI (images and seeds) of G_enc / G_ft / G (pp)" + SUF).split(" / ")
            assert msd(fz[2])[0] == msd(gm)[0] and fzc[2].strip() == gc.strip(), (bkey, fz[2], gm, fzc[2], gc)
            genc = cell1(msd(fz[0])[0], ci1(fzc[0])); gft = cell1(msd(fz[1])[0], ci1(fzc[1])); gg = cell1(msd(gm)[0], ci1(gc))
        sw = get(f"{bkey} / {fkey}: A / A_text / A_swap (%); A - A_swap / A_swap - A_text (pp)").split("; ")[1].split(" / ")
        swc = get(f"{bkey} / {fkey}: joint CI (images and seeds) of A - A_swap / A_swap - A_text (pp)").split(" / ")
        swap = cell1(msd(sw[0])[0], ci1(swc[0]))
        L.append(f"{fname} & {at_m} ({at_s}) & {pb} & {tf} & {grey} & & {genc} & {gft} & {gg} & {swap} \\\\")
    if bi < len(BASES) - 1: L.append(r"\addlinespace[2pt]")
L += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
(out / "table_results_4p.tex").write_text("\n".join(L) + "\n")
print("ok:", out / "table1_data.tex", out / "table_results_4p.tex", "numbers.csv", SHA)
